fn block_range(text: &str) -> io::Result<Option<std::ops::Range<usize>>> {
    crate::managed::block_range(text, BEGIN, END)
}

const BEGIN: &str = "# >>> tora completion >>>";
const END: &str = "# <<< tora completion <<<";
const PATH_PREFIX: &str = "# tora completion path: ";
const OWNER: &str = "# Generated by tora completion install.\n";

pub fn run(command: CompletionCommand) -> io::Result<()> {
    use CompletionCommand::*;
    let shell = match command {
        Bash => clap_complete::Shell::Bash,
        Zsh => clap_complete::Shell::Zsh,
        Fish => clap_complete::Shell::Fish,
        Powershell => clap_complete::Shell::PowerShell,
        Elvish => clap_complete::Shell::Elvish,
        Install { shell, path, yes } => return install(shell, path, yes),
    };
    let mut out = io::stdout().lock();
    clap_complete::generate(shell, &mut Cli::command(), "tora", &mut out);
    // The generated scripts are static. Bash and Zsh get a wrapper that asks
    // this binary for AWS profile names and otherwise defers to them.
    match shell {
        clap_complete::Shell::Bash => out.write_all(BASH_PROFILES.as_bytes()),
        clap_complete::Shell::Zsh => out.write_all(ZSH_PROFILES.as_bytes()),
        _ => Ok(()),
    }
}

// Profile names are data: never let the shell expand or word-split them.
const BASH_PROFILES: &str = r#"
_tora_dynamic() {
    local cur="${COMP_WORDS[COMP_CWORD]}" profile
    if [[ $cur != -* ]]; then
        COMPREPLY=()
        while IFS= read -r profile; do
            if [[ -n $profile && $profile == "$cur"* ]]; then
                printf -v profile %q "$profile"
                COMPREPLY+=("$profile")
            fi
        done < <(command tora __complete-aws-profiles -- "${COMP_WORDS[@]:1:COMP_CWORD-1}" 2>/dev/null)
        [[ ${#COMPREPLY[@]} -gt 0 ]] && return 0
    fi
    _tora "$@"
}

if [[ "${BASH_VERSINFO[0]}" -eq 4 && "${BASH_VERSINFO[1]}" -ge 4 || "${BASH_VERSINFO[0]}" -gt 4 ]]; then
    complete -F _tora_dynamic -o nosort -o bashdefault -o default tora
else
    complete -F _tora_dynamic -o bashdefault -o default tora
fi
"#;

const ZSH_PROFILES: &str = r#"
_tora_dynamic() {
    if [[ ${words[CURRENT]} != -* ]]; then
        local -a profiles
        local expl
        profiles=("${(@f)$(command tora __complete-aws-profiles -- "${(@)words[2,CURRENT-1]}" 2>/dev/null)}")
        profiles=("${(@)profiles:#}")
        if (( $#profiles )); then
            _wanted profiles expl 'AWS profile' compadd -a profiles
            return
        fi
    fi
    _tora "$@"
}

compdef _tora_dynamic tora
"#;

/// Whether the word after `words` is an AWS profile name: a positional argument
/// named `profile`, the value of a `--profile` option, or `config set aws.profile`.
fn completes_profile(words: &[OsString]) -> bool {
    let mut root = Cli::command();
    root.build();
    let mut command = &root;
    let mut positionals = Vec::new();
    let mut words = words.iter();
    while let Some(word) = words.next() {
        let Some(word) = word.to_str() else {
            return false;
        };
        if word == "--" {
            // Everything after the escape belongs to the wrapped command.
            return false;
        }
        let option = match word.strip_prefix("--") {
            // `--name=value` carries its own value.
            Some(long) if long.contains('=') => continue,
            Some(long) => command
                .get_arguments()
                .find(|arg| arg.get_long() == Some(long)),
            None if word.len() > 1 && word.starts_with('-') => command
                .get_arguments()
                .find(|arg| arg.get_short() == word.chars().last()),
            None => {
                match command.find_subcommand(word) {
                    Some(subcommand) if positionals.is_empty() => command = subcommand,
                    _ => positionals.push(word),
                }
                continue;
            }
        };
        // An option's separate value is not a positional argument.
        if let Some(option) = option.filter(|arg| arg.get_action().takes_values()) {
            if words.next().is_none() {
                return option.get_id() == "profile";
            }
        }
    }
    if command.get_name() == "set" && positionals.len() == 1 {
        let profile_key = ConfigKey::Profile.to_possible_value();
        return profile_key.is_some_and(|key| key.matches(positionals[0], false));
    }
    command
        .get_positionals()
        .nth(positionals.len())
        .is_some_and(|arg| arg.get_id() == "profile")
}

/// Answers the request the generated Bash/Zsh wrappers make on Tab:
/// `tora __complete-aws-profiles -- <words before the cursor>`.
/// It is not a clap subcommand, so it stays out of help and static completions.
pub fn answer_profile_request() -> bool {
    let mut args = env::args_os().skip(1);
    if args.next().as_deref() != Some("__complete-aws-profiles".as_ref()) {
        return false;
    }
    let words: Vec<_> = args.skip(1).collect();
    // Completion must stay quiet: a missing or failing AWS CLI means no candidates.
    if completes_profile(&words) {
        if let Ok(profiles) = crate::aws::completion_profiles() {
            let mut out = io::stdout().lock();
            for profile in profiles {
                // A closed pipe only means the shell stopped listening.
                let _ = writeln!(out, "{profile}");
            }
        }
    }
    true
}

impl InstallShell {
    fn name(self) -> &'static str {
        match self {
            Self::Bash => "bash",
            Self::Zsh => "zsh",
        }
    }
}

fn shell_name(value: &str) -> Option<InstallShell> {
    match Path::new(value.trim())
        .file_name()?
        .to_str()?
        .trim_start_matches('-')
    {
        "bash" => Some(InstallShell::Bash),
        "zsh" => Some(InstallShell::Zsh),
        _ => None,
    }
}

fn ps_field(field: &str, pid: &str) -> Option<String> {
    let output = Command::new("ps")
        .args(["-p", pid, "-o", field])
        .output()
        .ok()?;
    output
        .status
        .success()
        .then(|| String::from_utf8_lossy(&output.stdout).trim().to_owned())
}

fn detect_shell() -> Option<InstallShell> {
    let parent = ps_field("ppid=", &std::process::id().to_string());
    parent
        .and_then(|pid| ps_field("comm=", &pid))
        .and_then(|name| shell_name(&name))
        .or_else(|| env::var("SHELL").ok().and_then(|name| shell_name(&name)))
}

fn absolute(path: &Path, home: &Path) -> io::Result<PathBuf> {
    let path = if path == Path::new("~") {
        home.to_owned()
    } else if let Ok(rest) = path.strip_prefix("~/") {
        home.join(rest)
    } else if path.is_absolute() {
        path.to_owned()
    } else {
        env::current_dir()?.join(path)
    };
    let text = path
        .to_str()
        .ok_or_else(|| io::Error::other("path must be valid UTF-8"))?;
    if text.chars().any(char::is_control) {
        return Err(io::Error::other("path must not contain control characters"));
    }
    Ok(path)
}

fn quote(path: &Path) -> String {
    crate::shell::quote(path.to_str().expect("validated path"))
}

fn unmanaged(text: &str) -> bool {
    text.lines().any(|line| {
        let line = line.trim();
        !line.starts_with('#')
            && line.contains("tora")
            && (line.contains("completion") || line.contains("_tora") || line.contains("complete "))
    })
}

// `tora-use` switches the current shell, which a child process cannot do. It
// evaluates only a complete export statement from a successful `--export`, so a
// failed or cancelled login leaves the environment untouched. The body is
// shared by Bash and Zsh and stays safe under `set -eu`.
const USE_FUNCTION: &str = r#"function tora-use {
    local _tora_use_arg _tora_use_end= _tora_use_select=--select _tora_use_output
    for _tora_use_arg in ${1+"$@"}; do
        if [[ -n $_tora_use_end ]]; then
            _tora_use_select=
            break
        fi
        case $_tora_use_arg in
            --) _tora_use_end=1 ;;
            -h|--help)
                printf '%s\n' 'Usage: tora-use [--select] [--no-browser] [--use-device-code] [PROFILE]' \
                    'Switch this shell to an AWS profile, logging in through SSO only when needed.' \
                    'Without PROFILE, select one interactively. On failure nothing is changed.'
                return
                ;;
            --select) _tora_use_select= ;;
            -*) ;;
            *) _tora_use_select= ;;
        esac
    done
    _tora_use_output=$(command tora aws sso --export ${_tora_use_select:+"$_tora_use_select"} ${1+"$@"}) || return
    case $_tora_use_output in
        'unset AWS_'*) eval "$_tora_use_output" ;;
        *)
            printf '%s\n' 'tora-use: unexpected output from tora; environment unchanged' >&2
            return 1
            ;;
    esac
}
"#;

// Profile names are data, as in the `tora` completion wrappers. Here-strings
// instead of process substitution keep the file parseable in POSIX mode.
const BASH_USE_COMPLETION: &str = r#"_tora_use_complete() {
    local cur="${COMP_WORDS[COMP_CWORD]}" word
    COMPREPLY=()
    if [[ $cur == -* ]]; then
        while IFS= read -r word; do
            [[ -n $word ]] && COMPREPLY+=("$word")
        done <<< "$(compgen -W '--select --no-browser --use-device-code --help' -- "$cur")"
        return 0
    fi
    for word in "${COMP_WORDS[@]:1:COMP_CWORD-1}"; do
        [[ $word == --select ]] && return 0
    done
    while IFS= read -r word; do
        if [[ -n $word && $word == "$cur"* ]]; then
            printf -v word %q "$word"
            COMPREPLY+=("$word")
        fi
    done <<< "$(command tora __complete-aws-profiles -- aws sso "${COMP_WORDS[@]:1:COMP_CWORD-1}" 2>/dev/null)"
    return 0
}
complete -F _tora_use_complete tora-use
"#;

const ZSH_USE_COMPLETION: &str = r#"_tora_use() {
    local expl
    if [[ ${words[CURRENT]} == -* ]]; then
        local -a options
        options=(--select --no-browser --use-device-code --help)
        _wanted options expl option compadd -a options
        return
    fi
    # --select replaces the profile argument.
    (( ${${(@)words[2,CURRENT-1]}[(I)--select]} )) && return 1
    local -a profiles
    profiles=("${(@f)$(command tora __complete-aws-profiles -- aws sso "${(@)words[2,CURRENT-1]}" 2>/dev/null)}")
    profiles=("${(@)profiles:#}")
    (( $#profiles )) && _wanted profiles expl 'AWS profile' compadd -a profiles
}
"#;

fn loader(shell: InstallShell) -> String {
    let name = shell.name();
    let init = if shell == InstallShell::Zsh {
        "    if ! (( ${+functions[compdef]} )); then\n        autoload -Uz compinit\n        compinit\n    fi\n    (( ${+functions[compdef]} )) || return\n"
    } else {
        ""
    };
    // Leave the name to an alias, builtin or command that already owns it.
    let (owner, condition, completion, register) = match shell {
        InstallShell::Bash => ("type -t tora-use", "''|function", BASH_USE_COMPLETION, ""),
        InstallShell::Zsh => (
            "whence -w tora-use",
            "*': none'|*': function'",
            ZSH_USE_COMPLETION,
            "if (( ${+functions[_tora_use]} && ${+functions[compdef]} )); then\n    compdef _tora_use tora-use\nfi\n",
        ),
    };
    // Bash in POSIX mode (e.g. sh reading .profile) rejects the function name,
    // and the evaluated `tora completion bash` uses process substitution.
    let posix = if shell == InstallShell::Bash {
        "[[ :$SHELLOPTS: != *:posix:* ]] && "
    } else {
        ""
    };
    format!(
        "{OWNER}# Shell: {name}\n# Define tora-use, which switches this shell to an AWS profile.\nif {posix}case $({owner} 2>/dev/null) in {condition}) true ;; *) false ;; esac; then\n{USE_FUNCTION}{completion}fi\n# Generate completion from the current tora on each new shell.\nif {posix}[[ -z ${{_TORA_COMPLETION_{name}_LOADED-}} ]] && command -v tora >/dev/null 2>&1; then\n{init}    if _tora_completion_script=$(command tora completion {name}); then\n        eval \"$_tora_completion_script\"\n        _TORA_COMPLETION_{name}_LOADED=1\n    fi\n    unset _tora_completion_script\nfi\n{register}"
    )
}

fn startup_files(shell: InstallShell, home: &Path) -> io::Result<Vec<PathBuf>> {
    if shell == InstallShell::Zsh {
        let directory = env::var_os("ZDOTDIR")
            .map(PathBuf::from)
            .unwrap_or_else(|| home.to_owned());
        return Ok(vec![absolute(&directory.join(".zshrc"), home)?]);
    }
    // Login Bash reads only the first existing file in this order. Install a
    // guarded loader there too, without sourcing arbitrary .bashrc content.
    let mut files = vec![home.join(".bashrc")];
    let login = [".bash_profile", ".bash_login", ".profile"]
        .into_iter()
        .map(|name| home.join(name))
        .find(|path| path.exists() || path.is_symlink())
        .unwrap_or_else(|| home.join(".bash_profile"));
    files.push(login);
    Ok(files)
}

fn startup_block(shell: InstallShell, destination: &Path) -> String {
    format!(
        "{BEGIN}\n{PATH_PREFIX}{}\nif [ -n \"${{{}-}}\" ] && [ -r {} ]; then\n    . {}\nfi\n{END}",
        destination.display(),
        if shell == InstallShell::Bash {
            "BASH_VERSION"
        } else {
            "ZSH_VERSION"
        },
        quote(destination),
        quote(destination)
    )
}

fn install(shell: Option<InstallShell>, path: Option<PathBuf>, yes: bool) -> io::Result<()> {
    let interactive = io::stdin().is_terminal() && io::stderr().is_terminal();
    if !interactive && !yes {
        return Err(io::Error::other(
            "interactive terminal required; use --shell zsh|bash --yes for unattended installation",
        ));
    }
    let shell = match shell.or_else(detect_shell) {
        Some(shell) => shell,
        None => match Select::new()
            .with_prompt("Shell (Esc/q to cancel)")
            .items(["zsh", "bash"])
            .default(0)
            .interact_opt()
            .map_err(io::Error::other)?
        {
            Some(0) => InstallShell::Zsh,
            Some(_) => InstallShell::Bash,
            None => return Ok(()),
        },
    };
    eprintln!("Shell: {} (override with --shell)", shell.name());
    let home = env::var_os("HOME")
        .map(PathBuf::from)
        .ok_or_else(|| io::Error::other("HOME is required"))?;
    if !home.is_absolute() {
        return Err(io::Error::other("HOME must be an absolute path"));
    }
    let home = absolute(&home, &home)?;
    let files = startup_files(shell, &home)?;
    let mut existing_path = None;
    for file in &files {
        let text = read(file)?.unwrap_or_default();
        let range = block_range(&text)?;
        let outside = match range {
            Some(range) => {
                let stored = text[range.clone()]
                    .lines()
                    .find_map(|line| line.strip_prefix(PATH_PREFIX))
                    .ok_or_else(|| {
                        io::Error::other("managed completion block has no saved path")
                    })?;
                let stored = absolute(Path::new(stored), &home)?;
                if existing_path
                    .as_ref()
                    .is_some_and(|previous| previous != &stored)
                {
                    return Err(io::Error::other(
                        "startup files refer to different completion paths; reconcile them first",
                    ));
                }
                existing_path = Some(stored);
                format!("{}{}", &text[..range.start], &text[range.end..])
            }
            None => text,
        };
        if unmanaged(&outside) {
            return Err(io::Error::other(format!(
                "existing unmanaged tora completion in {}; keep it or remove it manually before installing",
                file.display()
            )));
        }
    }
    let root = crate::paths::home()?;
    let default = absolute(&root.join("completions").join(shell.name()), &home)?;
    let destination = match path.or(existing_path.clone()) {
        Some(path) => absolute(&path, &home)?,
        None if yes => default,
        None => {
            eprintln!("Existing completion configuration: none");
            let input: String = Input::new()
                .with_prompt("Completion loader file")
                .default(default.display().to_string())
                .interact_text()
                .map_err(io::Error::other)?;
            absolute(Path::new(&input), &home)?
        }
    };
    if destination.is_symlink() {
        return Err(io::Error::other("completion loader must not be a symlink"));
    }
    if let Some(text) = read(&destination)? {
        if !text.starts_with(OWNER) {
            return Err(io::Error::other(format!(
                "refusing to overwrite unmanaged file: {}",
                destination.display()
            )));
        }
        if !text
            .lines()
            .any(|line| line == format!("# Shell: {}", shell.name()))
        {
            return Err(io::Error::other(
                "completion loader belongs to a different shell; choose another --path",
            ));
        }
    }
    let mut changes = vec![Change::new(destination.clone(), loader(shell))?];
    let block = startup_block(shell, &destination);
    for file in files {
        let before = read(&file)?.unwrap_or_default();
        let after = replace_block(&before, block_range(&before)?, &block, "\n");
        changes.push(Change::new(file, after)?);
    }
    // Two startup paths may point to the same dotfile. Identical changes are
    // safe to coalesce; a loader/startup collision is never safe.
    let mut unique: Vec<Change> = Vec::new();
    for change in changes {
        if let Some(previous) = unique.iter().find(|previous| previous.path == change.path) {
            if previous.after != change.after {
                return Err(io::Error::other(
                    "completion and startup file paths overlap",
                ));
            }
        } else {
            unique.push(change);
        }
    }
    let changes: Vec<_> = unique.into_iter().filter(Change::changed).collect();
    if changes.is_empty() {
        eprintln!(
            "Completion is already installed and up to date: {}",
            destination.display()
        );
        return Ok(());
    }
    eprintln!("Files to create/update:");
    for change in &changes {
        eprintln!("  {}", change.path.display());
    }
    if !crate::managed::confirm("Install completion?", yes)? {
        eprintln!("Cancelled; no files changed.");
        return Ok(());
    }
    apply(&changes)?;
    eprintln!(
        "Completion installed. Open a new {} shell, or run:\n  source {}",
        shell.name(),
        quote(&destination)
    );
    if existing_path
        .as_ref()
        .is_some_and(|old| old != &destination)
    {
        eprintln!(
            "The previous loader was retained; it is no longer referenced by the managed configuration."
        );
    }
    Ok(())
}

/// Inspect the same managed startup files and custom loader paths as install.
/// This checks saved configuration, not whether a parent shell has sourced it.
pub fn diagnose() -> io::Result<String> {
    let shell = detect_shell().ok_or_else(|| {
        io::Error::other("could not detect Bash/Zsh; check SHELL or configure completion manually")
    })?;
    let home = env::var_os("HOME")
        .map(PathBuf::from)
        .ok_or_else(|| io::Error::other("HOME is required"))?;
    for file in startup_files(shell, &home)? {
        let text = read(&file)?.unwrap_or_default();
        let range = block_range(&text)?.ok_or_else(|| io::Error::other(format!("no managed completion in {}; run tora completion install --shell {} (manual setups cannot be verified)", file.display(), shell.name())))?;
        let path = text[range.clone()]
            .lines()
            .find_map(|line| line.strip_prefix(PATH_PREFIX))
            .ok_or_else(|| {
                io::Error::other(
                    "completion block has no saved loader path; run tora completion install",
                )
            })?;
        let loader_path = absolute(Path::new(path), &home)?;
        if text[range] != startup_block(shell, &loader_path) {
            return Err(io::Error::other(
                "completion startup block needs repair; run tora completion install",
            ));
        }
        let installed = read(&loader_path)?.ok_or_else(|| {
            io::Error::other(format!(
                "missing completion loader {}; run tora completion install",
                loader_path.display()
            ))
        })?;
        if installed != loader(shell) {
            return Err(io::Error::other(format!(
                "completion loader {} needs repair; run tora completion install",
                loader_path.display()
            )));
        }
    }
    Ok(format!(
        "{} completion configuration is installed (open a new shell to load it)",
        shell.name()
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_supported_shell_names_only() {
        assert_eq!(shell_name("/bin/zsh"), Some(InstallShell::Zsh));
        assert_eq!(shell_name("-bash"), Some(InstallShell::Bash));
        assert_eq!(shell_name("fish"), None);
        assert_eq!(shell_name("bash-helper"), None);
    }

    #[test]
    fn completes_profiles_only_where_a_profile_is_expected() {
        let at = |words: &[&str]| {
            completes_profile(&words.iter().map(OsString::from).collect::<Vec<_>>())
        };
        for words in [
            &["aws", "sso"][..],
            &["aws", "exec"],
            &["aws", "sso", "--no-browser"],
            &["aws", "sso", "--no-shell", "--use-device-code"],
            &["aws", "whoami"],
            &["aws", "status"],
            &["aws", "tunnel"],
            &["aws", "tunnel", "-t", "i-0aaa", "--remote", "db:5432"],
            &["aws", "exec", "--login"],
            &["aws", "exec", "--login", "--no-browser"],
            &["doctor", "--profile"],
            &["config", "set", "aws.profile"],
        ] {
            assert!(at(words), "{words:?}");
        }
        for words in [
            &[][..],
            &["aws"],
            &["aws", "profiles"],
            &["aws", "sso", "dev"],
            &["aws", "exec", "dev"],
            &["aws", "exec", "--"],
            &["aws", "exec", "dev", "--"],
            &["aws", "exec", "dev", "--", "aws", "sso"],
            &["aws", "help"],
            &["help", "aws", "sso"],
            &["update", "--version"],
            &["completion", "install", "--path"],
            &["aws", "whoami", "dev"],
            &["aws", "status", "dev"],
            &["aws", "tunnel", "dev"],
            &["aws", "tunnel", "--remote"],
            &["aws", "tunnel", "-l"],
            &["aws", "logout"],
            &["doctor"],
            &["doctor", "--profile", "dev"],
            &["doctor", "--profile=dev"],
            &["config", "set"],
            &["config", "set", "aws.region"],
            &["config", "set", "aws.profile", "dev"],
            &["config", "get"],
            &["config", "unset", "aws.profile"],
            &["aws", "exec", "--login", "dev", "--"],
        ] {
            assert!(!at(words), "{words:?}");
        }
    }
}
